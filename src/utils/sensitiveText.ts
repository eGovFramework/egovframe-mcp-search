/**
 * 민감한 식별번호 가림 처리.
 *
 * 개발자 지식은 공개 게시판(묻고답하기)의 글에서 만들어진다. 글쓴이가 본문에 적은 주민등록번호
 * 형식의 값이 그대로 들어 있을 수 있으므로, 색인할 때와 응답을 만들 때 그 형식을 가린다.
 */

/**
 * 주민등록번호·외국인등록번호 형식: 생년월일 6자리(월 01~12, 일 01~31), 하이픈, 1~8 로 시작하는 7자리.
 * 하이픈 앞뒤의 공백은 허용하고, 더 긴 숫자의 일부이면 일치하지 않는다.
 * 하이픈이 없는 13자리 숫자는 다른 값(타임스탬프, 일련번호)과 구별할 수 없어 대상에서 뺀다.
 */
const RESIDENT_NUMBER = /(?<!\d)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\s?-\s?[1-8]\d{6}(?!\d)/g;

/** 가린 자리에 넣는 표기 */
const RESIDENT_NUMBER_MASK = '******-*******';

/** 텍스트에서 주민등록번호 형식의 값을 가린다. */
export function maskResidentNumbers(text: string): string {
  return text.replace(RESIDENT_NUMBER, RESIDENT_NUMBER_MASK);
}
